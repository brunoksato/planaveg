-- As bacias como o arquivo as nomeia, porque ele não traz código: a região hidrográfica, a
-- mesobacia dentro dela e a bacia dentro da mesobacia. O nome da bacia se repete entre
-- mesobacias, como Araguari, no Amapá e em Minas Gerais. A carga as refaz.
