    nome text PRIMARY KEY
);

CREATE TABLE lugar_mesobacia (
    nome text PRIMARY KEY,
    regiao_hidrografica text NOT NULL REFERENCES lugar_regiao_hidrografica (nome)
);

CREATE TABLE lugar_bacia (
    mesobacia text NOT NULL REFERENCES lugar_mesobacia (nome),
    nome text NOT NULL,
    PRIMARY KEY (mesobacia, nome)
);

-- As regras: o contrato vigente em linhas. As views leem daqui; o portal lê as views catalogo_*.

-- Os anos de VS, cada um com a camada do arquivo.
CREATE TABLE contrato_ano (
    ano_vs smallint PRIMARY KEY CHECK (ano_vs BETWEEN 1985 AND 2100),
    camada text NOT NULL UNIQUE,
    rotulo text NOT NULL
);

CREATE TABLE contrato_grupo (
    grupo text PRIMARY KEY,
    titulo text NOT NULL
);

-- Os níveis da hierarquia do Anexo 1, pelo tier. motivo_ausencia: o nível que o arquivo não
-- traz, e por quê.
CREATE TABLE contrato_nivel (
    tier integer PRIMARY KEY CHECK (tier > 0),
    nivel text NOT NULL UNIQUE,
    grupo text NOT NULL REFERENCES contrato_grupo (grupo),
    titulo text NOT NULL,
    cor text NOT NULL CHECK (cor ~ '^#[0-9a-f]{6}$'),
    motivo_ausencia text
);

-- As condições do CAR da base, com a situação do cadastro da planilha de nomenclatura que as
-- junta: a que as saídas publicadas mostram.
--
-- Nas regras que o init-db atualiza linha a linha, a ordem e as outras chaves que não são a
-- primária só são conferidas no commit: uma linha nova no meio desloca as seguintes.
CREATE TABLE contrato_condicao_car (
    categoria text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE DEFERRABLE INITIALLY DEFERRED,
    situacao text NOT NULL
);

-- Cada rótulo de hierarquia que o arquivo traz, com o nível e a condição do CAR que ele diz. A
-- peça aponta para o rótulo: mudar o rótulo de uma linha (tier e condição) leva as peças junto.
CREATE TABLE contrato_hierarquia (
    hierarquia text PRIMARY KEY,
    tier integer NOT NULL REFERENCES contrato_nivel (tier),
    categoria text REFERENCES contrato_condicao_car (categoria),
    CONSTRAINT contrato_hierarquia_linha UNIQUE NULLS NOT DISTINCT (tier, categoria)
);

-- As marcas: a coluna do arquivo e o valor que a liga, a sigla na Sobreposicao e de onde a
-- marca sai (fonte sobreposicao: da sigla, não da coluna).
CREATE TABLE contrato_marca (
    marca text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE DEFERRABLE INITIALLY DEFERRED,
    coluna text NOT NULL UNIQUE DEFERRABLE INITIALLY DEFERRED,
    valor text NOT NULL,
    descricao text NOT NULL,
    sigla text UNIQUE DEFERRABLE INITIALLY DEFERRED,
    ordem_sigla integer UNIQUE DEFERRABLE INITIALLY DEFERRED,
    fonte text CHECK (fonte = 'sobreposicao'),
    CHECK ((sigla IS NULL) = (ordem_sigla IS NULL)),
    CHECK (fonte IS NULL OR sigla IS NOT NULL)
);

-- Os arranjos do Anexo 2, em ordem de prioridade. O complementar fica com o que nenhum outro
-- pegou; o ausente (motivo_ausencia) não tem regra e fica com 0 ha.
CREATE TABLE contrato_arranjo (
    arranjo text PRIMARY KEY,
    prioridade integer NOT NULL UNIQUE,
    titulo text NOT NULL,
    criterio text NOT NULL,
    cor text NOT NULL CHECK (cor ~ '^#[0-9a-f]{6}$'),
    meta_ha numeric CHECK (meta_ha > 0),
    meta_ano integer,
    complementar boolean NOT NULL,
    motivo_ausencia text,
    CHECK ((meta_ha IS NULL) = (meta_ano IS NULL)),
    CHECK (NOT (complementar AND motivo_ausencia IS NOT NULL))
);

CREATE UNIQUE INDEX contrato_arranjo_complementar ON contrato_arranjo (complementar)
    WHERE complementar;

-- A regra de cada arranjo em forma normal disjuntiva: vale se alguma alternativa vale, e uma
-- alternativa vale se todas as condições dela valem. Cada valor de uma condição é uma linha, que
-- aponta para a marca ou o nível que cita.
CREATE TABLE contrato_arranjo_condicao (
    arranjo text NOT NULL REFERENCES contrato_arranjo (arranjo) ON DELETE CASCADE,
    alternativa integer NOT NULL CHECK (alternativa > 0),
    condicao integer NOT NULL CHECK (condicao > 0),
    campo text NOT NULL CHECK (campo IN ('marca', 'nivel')),
    negada boolean NOT NULL,
    PRIMARY KEY (arranjo, alternativa, condicao),
    UNIQUE (arranjo, alternativa, condicao, campo)
);

CREATE TABLE contrato_arranjo_valor (
    arranjo text NOT NULL,
    alternativa integer NOT NULL,
    condicao integer NOT NULL,
    campo text NOT NULL,
    valor text NOT NULL,
    marca text GENERATED ALWAYS AS (CASE WHEN campo = 'marca' THEN valor END) STORED
        REFERENCES contrato_marca (marca),
    nivel text GENERATED ALWAYS AS (CASE WHEN campo = 'nivel' THEN valor END) STORED
        REFERENCES contrato_nivel (nivel),
    PRIMARY KEY (arranjo, alternativa, condicao, valor),
    FOREIGN KEY (arranjo, alternativa, condicao, campo)
        REFERENCES contrato_arranjo_condicao (arranjo, alternativa, condicao, campo)
        ON DELETE CASCADE
);

-- Os filtros do relatório. espacial: tem camada no mapa. tema: o portal o oferece como tema.
CREATE TABLE contrato_filtro (
    filtro text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE,
    grupo text NOT NULL,
    titulo text NOT NULL,
    subtitulo text,
    tipo text NOT NULL CHECK (tipo IN ('espacial', 'quantitativo', 'ambos')),
    espacial boolean NOT NULL GENERATED ALWAYS AS (tipo <> 'quantitativo') STORED,
    status text NOT NULL CHECK (status IN ('presente', 'parcial', 'vazio')),
    nota text,
    cor text NOT NULL CHECK (cor ~ '^#[0-9a-f]{6}$'),
    cql text NOT NULL,
    tema boolean NOT NULL,
    CHECK (NOT tema OR tipo <> 'quantitativo')
);

CREATE TABLE contrato_filtro_condicao (
    filtro text NOT NULL REFERENCES contrato_filtro (filtro) ON DELETE CASCADE,
    alternativa integer NOT NULL CHECK (alternativa > 0),
    condicao integer NOT NULL CHECK (condicao > 0),
    campo text NOT NULL CHECK (campo IN ('marca', 'nivel', 'arranjo')),
    negada boolean NOT NULL,
    PRIMARY KEY (filtro, alternativa, condicao),
    UNIQUE (filtro, alternativa, condicao, campo)
);

CREATE TABLE contrato_filtro_valor (
    filtro text NOT NULL,
    alternativa integer NOT NULL,
    condicao integer NOT NULL,
    campo text NOT NULL,
    valor text NOT NULL,
    marca text GENERATED ALWAYS AS (CASE WHEN campo = 'marca' THEN valor END) STORED
        REFERENCES contrato_marca (marca),
    nivel text GENERATED ALWAYS AS (CASE WHEN campo = 'nivel' THEN valor END) STORED
        REFERENCES contrato_nivel (nivel),
    arranjo text GENERATED ALWAYS AS (CASE WHEN campo = 'arranjo' THEN valor END) STORED
        REFERENCES contrato_arranjo (arranjo),
    PRIMARY KEY (filtro, alternativa, condicao, valor),
    FOREIGN KEY (filtro, alternativa, condicao, campo)
        REFERENCES contrato_filtro_condicao (filtro, alternativa, condicao, campo)
        ON DELETE CASCADE
);

-- Os recortes territoriais dos números.
CREATE TABLE contrato_dimensao (
    dimensao text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE,
    grupo text NOT NULL,
    titulo text NOT NULL
);

-- O que o relatório pede e a base não traz.
CREATE TABLE contrato_fonte_ausente (
    codigo text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE,
    grupo text NOT NULL,
    descricao text NOT NULL
);

-- As camadas de mapa que o init-db gera do contrato, com o tipo, o filtro, o ano e os estilos.
CREATE TABLE camada_publicada (
    camada text PRIMARY KEY,
    ordem integer NOT NULL UNIQUE,
    tipo text NOT NULL CHECK (tipo IN ('peca', 'espacial', 'municipio')),
    filtro text REFERENCES contrato_filtro (filtro),
    ano_vs smallint REFERENCES contrato_ano (ano_vs),
    titulo text NOT NULL,
    estilo text NOT NULL,
    estilos_alternativos text[] NOT NULL DEFAULT '{}',
    CHECK ((tipo = 'espacial') = (filtro IS NOT NULL)),
    CHECK (tipo <> 'espacial' OR ano_vs IS NOT NULL)
);

-- A entrega pronta. A peça é um registro de um ano: o que o arquivo diz dela (peca_recebida), as
-- marcas (peca_marca) e o desenho (peca_geometria), com a mesma chave. origem_id é o fid do
-- GeoPackage, único só dentro da camada e renumerado a cada entrega.
CREATE TABLE peca_recebida (
    entrega_id uuid NOT NULL,
    ano_vs smallint NOT NULL,
    origem_id bigint NOT NULL,
    hierarquia text NOT NULL REFERENCES contrato_hierarquia (hierarquia) ON UPDATE CASCADE,
    area_ha double precision NOT NULL CHECK (area_ha >= 0),
    -- NULL: fora dos limites estaduais (o arquivo diz FORA). Uma peça de borda pode ter outra UF
    -- que a do município: a do limite estadual onde ela cai.
    uf char(2) REFERENCES lugar_uf (sigla),
    -- NULL: fora dos limites dos biomas (o arquivo diz FORA).
    bioma text REFERENCES lugar_bioma (nome),
    cod_municipio char(7) NOT NULL REFERENCES lugar_municipio (codigo),
    bacia_meso text NOT NULL,
    bacia text NOT NULL,
    -- As siglas das marcas fundiárias como o arquivo as juntou: o verify confere com as marcas.
    sobreposicao text,
    PRIMARY KEY (entrega_id, ano_vs, origem_id),
    FOREIGN KEY (entrega_id, ano_vs) REFERENCES entrega_camada (entrega_id, ano_vs)
        ON DELETE CASCADE,
    FOREIGN KEY (bacia_meso, bacia) REFERENCES lugar_bacia (mesobacia, nome)
);

-- A chave estrangeira para lugar_municipio: tirar um município da lista confere as peças por aqui.
CREATE INDEX peca_recebida_municipio ON peca_recebida (cod_municipio, ano_vs);

-- As marcas de cada peça, uma por linha. A carga grava a peça, as marcas e o desenho numa
-- sentença só: as chaves das duas tabelas da peça são conferidas no commit.
CREATE TABLE peca_marca (
    entrega_id uuid NOT NULL,
    ano_vs smallint NOT NULL,
    origem_id bigint NOT NULL,
    marca text NOT NULL REFERENCES contrato_marca (marca),
    PRIMARY KEY (entrega_id, ano_vs, origem_id, marca),
    FOREIGN KEY (entrega_id, ano_vs, origem_id)
        REFERENCES peca_recebida (entrega_id, ano_vs, origem_id)
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- O desenho de cada peça: a geometria recebida (Albers IBGE, onde área e sobreposição são
-- medidas), as formas que o mapa lê e o que se mede nela.
CREATE TABLE peca_geometria (
    entrega_id uuid NOT NULL,
    ano_vs smallint NOT NULL,
    origem_id bigint NOT NULL,
    geom_albers geometry(MultiPolygon, 100000) NOT NULL,
    geom geometry(MultiPolygon, 4674) NOT NULL,
    geom_alta geometry(MultiPolygon, 4674),
    ponto geometry(Point, 4674) NOT NULL,
    area_calculada_ha numeric(24,8) NOT NULL CHECK (area_calculada_ha >= 0),
    partes integer NOT NULL CHECK (partes > 0),
    PRIMARY KEY (entrega_id, ano_vs, origem_id),
    FOREIGN KEY (entrega_id, ano_vs, origem_id)
        REFERENCES peca_recebida (entrega_id, ano_vs, origem_id)
        ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- O clique acha a peça pelo ano e pelo fid (peca_parte).
CREATE INDEX peca_geometria_peca ON peca_geometria (ano_vs, origem_id);

-- O GeoServer desenha a simplificada até o zoom 13, a inteira do 14 em diante e o ponto: sem
-- índice nelas, cada tile varre a tabela inteira.
CREATE INDEX peca_geometria_gist ON peca_geometria USING gist (geom);

CREATE INDEX peca_geometria_gist_alta ON peca_geometria USING gist (geom_alta);

CREATE INDEX peca_geometria_gist_ponto ON peca_geometria USING gist (ponto);

-- O cômputo que o arquivo diz para cada linha da hierarquia em cada ano: um valor só, que o
-- arquivo repete em cada peça. O verify confere que é a soma das peças.
CREATE TABLE computo_recebido (
    entrega_id uuid NOT NULL,
    ano_vs smallint NOT NULL,
    hierarquia text NOT NULL REFERENCES contrato_hierarquia (hierarquia) ON UPDATE CASCADE,
    area_ha double precision NOT NULL CHECK (area_ha >= 0),
    PRIMARY KEY (entrega_id, ano_vs, hierarquia),
    FOREIGN KEY (entrega_id, ano_vs) REFERENCES entrega_camada (entrega_id, ano_vs)
        ON DELETE CASCADE
);

-- A tabela de chaves do GeoServer: declara fid como chave de cada camada de mapa publicada, para
-- ids estáveis. O init-db a preenche com as views geradas. As consultas com parâmetros
-- (peca_parte) levam a chave na própria definição no GeoServer (keyColumn).
CREATE TABLE gt_pk_metadata (
    table_schema varchar(63) NOT NULL,
    table_name varchar(63) NOT NULL,
    pk_column varchar(63) NOT NULL,
    pk_column_idx integer,
    pk_policy varchar(32),
    pk_sequence varchar(64),
    UNIQUE (table_schema, table_name, pk_column),
    CHECK (pk_policy IN ('sequence', 'assigned', 'autogenerated'))
);
