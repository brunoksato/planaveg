-- O modelo do banco do planaveg_core num banco vazio. As migrações seguintes mudam só o que for
-- preciso, sem perder o que o arquivo não refaz: as versões do contrato, as entregas, as
-- execuções, as publicações e os números de cada uma.
--
-- Quatro partes, cada uma com a sua regra de vida:
-- - o registro (contrato_versao, entrega, entrega_camada, execucao, publicacao, resultado_*):
--   guardado para sempre;
-- - os lugares (lugar_*): as UFs e os biomas daqui, os municípios do IBGE (o init-db os refaz do
--   arquivo do pacote) e as bacias que a carga traz do arquivo;
-- - as regras (contrato_* e camada_publicada): o contrato vigente em linhas, que o init-db
--   atualiza no lugar. Apagar uma linha que as peças usam falha: pede init-db --recreate;
-- - a entrega pronta (peca_*, computo_recebido): a carga refaz.

-- O contrato: cada versão do JSON, para sempre. impressao é o SHA-256 do JSON canônico, e
-- impressao_carga, o do que a carga lê dele: as camadas, as colunas e as siglas da Sobreposicao.
-- A vigente é a que as tabelas contrato_* trazem agora. O init-db a troca, e as outras etapas
-- param se o contrato configurado não for ela.
CREATE TABLE contrato_versao (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    impressao char(64) NOT NULL UNIQUE CHECK (impressao ~ '^[0-9a-f]{64}$'),
    versao text NOT NULL,
    impressao_carga char(64) NOT NULL CHECK (impressao_carga ~ '^[0-9a-f]{64}$'),
    conteudo jsonb NOT NULL,
    registrada_em timestamptz NOT NULL DEFAULT now(),
    vigente boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX contrato_versao_uma_vigente ON contrato_versao ((true)) WHERE vigente;

-- O arquivo carregado, pelo conteúdo e pela versão do contrato com que foi lido: recarregar os
-- dois reaproveita a linha. Uma entrega pronta, no máximo: a carga troca a anterior pela nova
-- numa transação só.
CREATE TABLE entrega (
    id uuid PRIMARY KEY,
    nome_arquivo text NOT NULL,
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    tamanho_bytes bigint NOT NULL CHECK (tamanho_bytes >= 0),
    application_id integer NOT NULL,
    user_version integer NOT NULL,
    contrato_versao_id integer NOT NULL REFERENCES contrato_versao (id),
    iniciada_em timestamptz NOT NULL DEFAULT now(),
    concluida_em timestamptz,
    estado text NOT NULL DEFAULT 'carregando'
        CHECK (estado IN ('carregando', 'pronta', 'substituida', 'falhou')),
    UNIQUE (sha256, contrato_versao_id),
    CHECK (estado <> 'pronta' OR concluida_em IS NOT NULL)
);

CREATE UNIQUE INDEX entrega_uma_pronta ON entrega ((true)) WHERE estado = 'pronta';

-- Cada camada do arquivo numa entrega: o ano de VS e o que a carga contou nela. feicoes é a
-- contagem do arquivo, feita à parte da leitura; a geometria vazia não entra (vazias).
CREATE TABLE entrega_camada (
    entrega_id uuid NOT NULL REFERENCES entrega (id) ON DELETE CASCADE,
    ano_vs smallint NOT NULL CHECK (ano_vs BETWEEN 1985 AND 2100),
    camada text NOT NULL,
    feicoes integer NOT NULL CHECK (feicoes >= 0),
    lidas integer NOT NULL CHECK (lidas >= 0),
    carregadas integer NOT NULL CHECK (carregadas >= 0),
    vazias integer NOT NULL CHECK (vazias >= 0),
    -- Os valores que não converteram numa coluna anulável e viraram NULL, por coluna.
    anuladas jsonb NOT NULL DEFAULT '{}'::jsonb,
    area_ha double precision NOT NULL CHECK (area_ha >= 0),
    PRIMARY KEY (entrega_id, ano_vs),
    UNIQUE (entrega_id, camada),
    CHECK (carregadas <= lidas)
);

-- Cada etapa que roda: abre a linha antes e a fecha com ok e o detalhe.
CREATE TABLE execucao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrega_id uuid REFERENCES entrega (id) ON DELETE CASCADE,
    etapa text NOT NULL CHECK (etapa IN ('init-db', 'load', 'verify', 'geoserver')),
    iniciada_em timestamptz NOT NULL DEFAULT now(),
    concluida_em timestamptz,
    ok boolean,
    detalhe jsonb NOT NULL DEFAULT '{}'::jsonb,
    versao_lab text,
    erro text,
    CHECK ((concluida_em IS NULL) = (ok IS NULL))
);

CREATE INDEX execucao_entrega_etapa ON execucao (entrega_id, etapa, iniciada_em DESC);

-- Cada publicação que mudou os dados (a versao_dados): de que entrega, com que contrato e com que
-- versões. Os números que ela pôs no ar ficam nas tabelas resultado_*, que só se apagam com ela.
CREATE TABLE publicacao (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    entrega_id uuid NOT NULL REFERENCES entrega (id),
    contrato_versao_id integer NOT NULL REFERENCES contrato_versao (id),
    versao_mapa text NOT NULL CHECK (versao_mapa ~ '^[0-9a-f]{16}$'),
    versao_dados text NOT NULL CHECK (versao_dados ~ '^[0-9a-f]{16}$'),
    publicada_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX publicacao_entrega ON publicacao (entrega_id, publicada_em DESC);

-- O cômputo de cada linha da hierarquia, como a publicação o mostrou (quantitativo_nivel).
CREATE TABLE resultado_nivel (
    publicacao_id integer NOT NULL REFERENCES publicacao (id) ON DELETE CASCADE,
    ano_vs smallint NOT NULL,
    tier integer NOT NULL,
    categoria text,
    n_pecas bigint NOT NULL CHECK (n_pecas >= 0),
    area_ha double precision NOT NULL,
    computo_recebido_ha double precision,
    area_calculada_ha numeric NOT NULL,
    UNIQUE NULLS NOT DISTINCT (publicacao_id, ano_vs, tier, categoria)
);

-- Cada recorte em cada ano (o total, os níveis, os arranjos, os filtros e os lugares), como a
-- publicação o mostrou (serie).
CREATE TABLE resultado_serie (
    publicacao_id integer NOT NULL REFERENCES publicacao (id) ON DELETE CASCADE,
    recorte text NOT NULL,
    chave text,
    rotulo text,
    ano_vs smallint NOT NULL,
    area_ha double precision,
    UNIQUE NULLS NOT DISTINCT (publicacao_id, recorte, chave, ano_vs)
);

-- As facetas, de onde o portal tira qualquer total do Brasil (quantitativo_faceta).
CREATE TABLE resultado_faceta (
    publicacao_id integer NOT NULL REFERENCES publicacao (id) ON DELETE CASCADE,
    ano_vs smallint NOT NULL,
    nivel text,
    categoria text,
    arranjo text,
    uf text,
    bioma text,
    temas text NOT NULL,
    esferas_uc text NOT NULL,
    tipos_uc text NOT NULL,
    n_pecas integer NOT NULL CHECK (n_pecas >= 0),
    n_poligonos integer NOT NULL CHECK (n_poligonos >= 0),
    area_ha double precision NOT NULL,
    UNIQUE NULLS NOT DISTINCT (publicacao_id, ano_vs, nivel, categoria, arranjo, uf, bioma, temas,
                               esferas_uc, tipos_uc)
);

